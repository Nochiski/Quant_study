"""시스템 프롬프트 템플릿 (설계 spec D8).

프롬프트는 application이 소유한다. 전략 언어 요약(최상위 키·노드 kind·연산자 enum)과 도구 이름은
여기에 손으로 적지 않고 runtime schema와 domain 상수에서 채워 넣는다. 손으로 적으면 스키마가
바뀔 때 프롬프트가 조용히 stale해지고, 모델이 존재하지 않는 필드를 쓴 제안을 반복한다.

그래서 이 파일에는 "어떻게 일할지"만 있고 "무엇이 있는지"는 자리표시자로만 있다.
"""

